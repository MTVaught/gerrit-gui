// Build the real Monaco sanitizer paths, then run browser probes through a mouse click.
// xvfb-run -a node_modules/.bin/electron --no-sandbox test/security-dependencies-ui.cjs
const { app, BrowserWindow, nativeTheme } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const rawFs = require('original-fs')
const os = require('node:os')
const path = require('node:path')
const { createHash } = require('node:crypto')
const taskData = fs.mkdtempSync(path.join(os.tmpdir(), 'gerrit-security-dependencies-'))
app.setPath('userData', path.join(taskData, 'profile'))
app.disableHardwareAcceleration()
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
const timeout = setTimeout(() => app.exit(2), 60000)
app.whenReady().then(async () => {
  const root = path.join(__dirname, '..')
  const artifacts = JSON.parse(fs.readFileSync(path.join(root, 'docs/security-dependencies/artifacts.json'), 'utf8'))
  const hash = name => createHash('sha256').update(rawFs.readFileSync(path.join(root, name))).digest('hex')
  assert.equal(hash(artifacts.archive.path), artifacts.archive.sha256, 'report matches the actual packaged archive')
  assert.equal(hash('pnpm-lock.yaml'), artifacts.lockfileSha256, 'report matches current dependencies')
  assert.equal(hash('patches/monaco-editor@0.57.0.patch'), artifacts.patchSha256, 'report matches current Monaco patch')
  const { build } = await import('vite')
  const buildDir = path.join(taskData, 'build')
  await build({ configFile: false, root: path.join(__dirname, 'fixtures'), base: './', logLevel: 'warn',
    build: { outDir: buildDir, emptyOutDir: true, rollupOptions: { input: path.join(__dirname, 'fixtures/security-dependencies.html') } } })
  const win = new BrowserWindow({ width: 1240, height: 940, useContentSize: true, webPreferences: { contextIsolation: true, sandbox: true } })
  const run = script => win.webContents.executeJavaScript(script)
  const dir = path.join(__dirname, '../docs/screenshots/security-dependencies')
  fs.mkdirSync(dir, { recursive: true })
  for (const theme of ['light', 'dark']) {
    nativeTheme.themeSource = theme
    await win.loadFile(path.join(buildDir, 'security-dependencies.html'))
    for (let i = 0; i < 100 && !await run(`document.querySelector('#version').textContent.includes('DOMPurify')`); i++) await delay(50)
    const rect = await run(`document.querySelector('#run').getBoundingClientRect().toJSON()`)
    const point = { x: Math.round(rect.x + rect.width / 2), y: Math.round(rect.y + rect.height / 2) }
    win.focus(); win.webContents.focus()
    win.webContents.sendInputEvent({ type: 'mouseMove', ...point })
    await delay(200)
    for (const type of ['mouseDown', 'mouseUp']) win.webContents.sendInputEvent({ type, ...point, button: 'left', clickCount: 1 })
    for (let i = 0; i < 100 && !await run('Boolean(window.securityResult)'); i++) await delay(50)
    const result = await run('window.securityResult')
    assert.ok(result, 'mouse click ran the probes')
    assert.ok(result.checks.every(check => check.passed), JSON.stringify(result))
    assert.equal(result.version, '3.4.17')
    await delay(200)
    fs.writeFileSync(path.join(dir, `sanitizer-${theme}.png`), (await win.webContents.capturePage()).toPNG())
    fs.writeFileSync(path.join(dir, `sanitizer-${theme}.json`), JSON.stringify(result, null, 2) + '\n')
    console.log(JSON.stringify({ theme, archiveSha256: artifacts.archive.sha256, ...result }))
  }
  clearTimeout(timeout)
  win.destroy()
  app.quit()
}).catch(error => { console.error(error); app.exit(1) }).finally(() => fs.rmSync(taskData, { recursive: true, force: true }))
