// Run under an isolated 1280x960 Xvfb display. Records real X11 input.
const { app, BrowserWindow, nativeTheme } = require('electron')
const { spawn, execFile } = require('node:child_process')
const { promisify } = require('node:util')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const assert = require('node:assert/strict')
const { controls, longMessage } = require('./review-comment-field-checks.cjs')
process.env.REVIEW_COMMENTS_FIXTURE = '1'
process.env.REVIEW_PORTED_FIXTURE = '1'
process.env.REVIEW_FIXTURE_NOW = '2026-10-21 12:00:00.000'
app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), 'comment-scroll-record-')))
app.disableHardwareAcceleration()
app.on('window-all-closed', () => {})
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
const directory = path.resolve(__dirname, '../openspec/changes/enable-comment-field-scrolling/evidence')
fs.mkdirSync(directory, { recursive: true })
const input = (...args) => promisify(execFile)('xdotool', args.map(String)).then(result => result.stdout)
const timeout = setTimeout(() => app.exit(2), 180000)
app.whenReady().then(async () => {
  const results = []
  for (const theme of ['light', 'dark']) {
    nativeTheme.themeSource = theme
    const win = new BrowserWindow({ x: 0, y: 0, width: 1280, height: 900, frame: false, useContentSize: true, webPreferences: { contextIsolation: true, sandbox: false, preload: path.join(__dirname, 'fixtures/local-review-preload.cjs') } })
    const { run, press, until, button, fill, panes } = controls(win)
    const caption = new BrowserWindow({ x: 0, y: 900, width: 1280, height: 60, frame: false, focusable: false, backgroundColor: '#171b22', webPreferences: { sandbox: true } })
    await caption.loadURL('data:text/html,' + encodeURIComponent('<body style="margin:0;padding:16px 24px;color:white;background:#171b22;font:18px system-ui"><div id="caption"></div></body>'))
    const say = text => caption.webContents.executeJavaScript(`document.querySelector('#caption').textContent = ${JSON.stringify(text)}`)
    await win.loadFile(path.join(__dirname, '../out/renderer/index.html'))
    await until(`Boolean(document.querySelector('.review-main'))`)
    await run(`document.querySelector('.review-main').click()`)
    await until(`document.querySelector('.review-editor')?.dataset.reviewReady === 'true'`)
    win.focus(); win.webContents.focus()
    await button('Go to line'); await press('a', ['control']); await win.webContents.insertText(':40'); await press('Enter'); await press('c')
    await until(`document.activeElement?.getAttribute('aria-label') === 'Draft comment'`)
    await fill('[aria-label="Draft comment"]', longMessage)
    // Give the text enough height to read during the recording. Native resize
    // behavior is separately tested through the real corner handle.
    await run(`document.querySelector('[aria-label="Draft comment"]').style.height = '160px'`)
    await press('Home', ['control']); await delay(600)
    const rect = await run(`document.querySelector('[aria-label="Draft comment"]').getBoundingClientRect().toJSON()`)
    assert.ok(rect.bottom < 870, 'recorded field fits the window')
    const x = Math.round(rect.x + rect.width / 2), y = Math.round(rect.y + rect.height / 2)
    await input('mousemove', 20, 20)
    await say('Linux Electron · simulated Gerrit data. Scroll within the long draft.')
    const file = path.join(directory, 'comment-scroll-' + theme + '.mp4')
    const recorder = spawn('ffmpeg', ['-y', '-f', 'x11grab', '-draw_mouse', '1', '-framerate', '25', '-video_size', '1280x960', '-i', process.env.DISPLAY, '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '20', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', file], { stdio: ['pipe', fs.openSync(path.join(directory, 'record-' + theme + '.log'), 'w'), 'pipe'] })
    recorder.stderr.on('data', () => {})
    const exited = new Promise((resolve, reject) => { recorder.on('error', reject); recorder.on('exit', code => code === 0 ? resolve() : reject(new Error('FFmpeg exited ' + code))) })
    await delay(1000)
    async function move(toX, toY) {
      const from = await input('getmouselocation', '--shell')
      const fromX = Number(from.match(/X=(\d+)/)[1]), fromY = Number(from.match(/Y=(\d+)/)[1])
      for (let i = 1; i <= 20; i++) { await input('mousemove', Math.round(fromX + (toX - fromX) * i / 20), Math.round(fromY + (toY - fromY) * i / 20)); await delay(50) }
      await delay(2000)
    }
    await move(x, y); await input('click', 1); await delay(400)
    const before = await panes()
    await input('click', '--repeat', 3, '--delay', 350, 5); await delay(1800)
    const middle = await run(`document.querySelector('[aria-label="Draft comment"]').scrollTop`)
    assert.ok(middle > 0); assert.deepEqual(await panes(), before)
    await say('Scroll to the last line. The field size and both code panes stay fixed.')
    await input('click', '--repeat', 40, '--delay', 100, 5); await delay(1800)
    const bottom = await run(`(() => { const f=document.querySelector('[aria-label="Draft comment"]'); return { top:f.scrollTop, max:f.scrollHeight-f.clientHeight } })()`)
    assert.equal(bottom.top, bottom.max)
    await say('At the bottom, more scrolling keeps the code in place.')
    await input('click', '--repeat', 4, '--delay', 350, 5); await delay(1800)
    assert.deepEqual(await panes(), before)
    await say('Scroll back to the first line inside the same field.')
    await input('click', '--repeat', 40, '--delay', 100, 4); await delay(1800)
    assert.equal(await run(`document.querySelector('[aria-label="Draft comment"]').scrollTop`), 0)
    await say('Move the pointer over code. The diff now scrolls normally.')
    await move(Math.round(rect.x + 80), Math.round(Math.max(140, rect.y - 55)))
    await input('click', '--repeat', 3, '--delay', 350, 5); await delay(2200)
    assert.notDeepEqual(await panes(), before)
    await say('Text is unchanged. Scrolling works in the field and over the code.')
    await delay(2200)
    assert.equal(await run(`document.querySelector('[aria-label="Draft comment"]').value`), longMessage)
    recorder.stdin.write('q'); await exited
    results.push({ theme, file, platform: 'Linux X11', electron: process.versions.electron, middle, bottom, before, after: await panes(), input: 'xdotool pointer, click and physical wheel button input', data: 'simulated Gerrit fixture' })
    win.destroy(); caption.destroy()
  }
  fs.writeFileSync(path.join(directory, 'recording-results.json'), JSON.stringify(results, null, 2) + '\n')
  clearTimeout(timeout); app.quit()
}).catch(error => { console.error(error); app.exit(1) })
